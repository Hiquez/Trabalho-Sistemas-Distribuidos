#!/bin/bash
set -e
# Oracle image sources init scripts; DB_PASSWORD is supplied by Compose.
[[ "$DB_PASSWORD" =~ ^[a-zA-Z0-9_]+$ ]] || { echo 'DB_PASSWORD deve conter letras, números ou underscore'; exit 1; }
sqlplus -s / as sysdba <<SQL
WHENEVER SQLERROR EXIT SQL.SQLCODE
ALTER SESSION SET CONTAINER=FREEPDB1;
CREATE USER SOLICITACOES IDENTIFIED BY "$DB_PASSWORD";
CREATE USER AGENDA_CAPACIDADE IDENTIFIED BY "$DB_PASSWORD";
CREATE USER COOPERATIVA IDENTIFIED BY "$DB_PASSWORD";
CREATE USER COLETAS_DESTINACAO IDENTIFIED BY "$DB_PASSWORD";
GRANT CONNECT, RESOURCE, UNLIMITED TABLESPACE TO SOLICITACOES, AGENDA_CAPACIDADE, COOPERATIVA, COLETAS_DESTINACAO;
EXIT;
SQL
