#!/bin/bash
set -e
# Oracle image sources init scripts; DB_PASSWORD is supplied by Compose.
for password in "$SOLICITACOES_PASSWORD" "$AGENDA_CAPACIDADE_PASSWORD" "$COOPERATIVA_PASSWORD" "$COLETAS_DESTINACAO_PASSWORD"; do
[[ "$password" =~ ^[a-zA-Z0-9_]+$ ]] || { echo 'DB_PASSWORD deve conter letras, números ou underscore'; exit 1; }
done
sqlplus -s / as sysdba <<SQL
WHENEVER SQLERROR EXIT SQL.SQLCODE
ALTER SESSION SET CONTAINER=FREEPDB1;
CREATE USER SOLICITACOES IDENTIFIED BY "$SOLICITACOES_PASSWORD";
CREATE USER AGENDA_CAPACIDADE IDENTIFIED BY "$AGENDA_CAPACIDADE_PASSWORD";
CREATE USER COOPERATIVA IDENTIFIED BY "$COOPERATIVA_PASSWORD";
CREATE USER COLETAS_DESTINACAO IDENTIFIED BY "$COLETAS_DESTINACAO_PASSWORD";
GRANT CONNECT, RESOURCE, UNLIMITED TABLESPACE TO SOLICITACOES, AGENDA_CAPACIDADE, COOPERATIVA, COLETAS_DESTINACAO;
EXIT;
SQL
